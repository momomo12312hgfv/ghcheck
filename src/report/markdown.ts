import pkg from "../../package.json";
import type { Report } from "../core/types";

function cell(value: string | number | null | undefined): string {
  return String(value ?? "—")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ");
}

export function renderMarkdown(report: Report): string {
  const lines: string[] = [];
  lines.push("# ghcheck report");
  lines.push("");
  lines.push(
    `Generated by [ghcheck](https://github.com/momomo12312hgfv/ghcheck) v${pkg.version} at ${report.generatedAt}.`,
  );
  lines.push("");

  lines.push("## Blast radius");
  lines.push("");
  lines.push(`**${report.score.level.toUpperCase()}** — ${report.score.value}/100`);
  if (report.score.rawValue !== report.score.value) {
    lines.push("");
    lines.push(
      `Raw weighted score: ${report.score.rawValue}. The score was raised to the minimum floor for the highest severity found.`,
    );
  }
  lines.push("");

  if (report.token) {
    lines.push("## Token");
    lines.push("");
    lines.push("| Field | Value |");
    lines.push("| --- | --- |");
    lines.push(`| Identity | ${cell(report.token.identity ?? "—")} |`);
    lines.push(`| Token | \`${cell(report.token.redacted)}\` (${cell(report.token.typeLabel)}) |`);
    lines.push(
      `| Scopes | ${report.token.scopes.length > 0 ? report.token.scopes.map((scope) => `\`${scope}\``).join(", ") : "none"} |`,
    );
    if (report.token.permissions.length > 0) {
      lines.push(
        `| Permissions (self-reported) | ${report.token.permissions
          .map((permission) => `\`${permission.permission}=${permission.access}\``)
          .join(", ")} |`,
      );
    }
    lines.push("");
  }
  lines.push("## Summary");
  lines.push("");
  lines.push("| Analyzer | Findings | Critical | High | Medium | Low |");
  lines.push("| --- | --- | --- | --- | --- | --- |");
  for (const [analyzer, bucket] of Object.entries(report.summary)) {
    lines.push(
      `| ${cell(analyzer)} | ${bucket.total} | ${bucket.bySeverity.critical} | ${bucket.bySeverity.high} | ${bucket.bySeverity.medium} | ${bucket.bySeverity.low} |`,
    );
  }
  lines.push("");

  if (report.findings.length > 0) {
    lines.push("## Findings");
    lines.push("");
    lines.push("| Severity | Rule | Location | Finding |");
    lines.push("| --- | --- | --- | --- |");
    for (const finding of report.findings) {
      const location = finding.location
        ? `\`${cell(finding.location.file)}:${finding.location.line}\``
        : "—";
      lines.push(
        `| ${finding.severity} | \`${cell(finding.id)}\` | ${location} | ${cell(finding.title)} |`,
      );
    }
    lines.push("");

    lines.push("## Details");
    lines.push("");
    for (const finding of report.findings) {
      const location = finding.location
        ? `\`${cell(finding.location.file)}:${finding.location.line}\``
        : "—";
      lines.push(`### ${finding.title}`);
      lines.push("");
      lines.push(`- **Rule**: \`${finding.id}\``);
      lines.push(`- **Severity**: ${finding.severity}`);
      if (finding.confidence) lines.push(`- **Confidence**: ${finding.confidence}`);
      lines.push(`- **Location**: ${location}`);
      if (finding.evidence) lines.push(`- **Evidence**: \`${cell(finding.evidence)}\``);
      if (finding.grantedBy?.length) {
        lines.push(`- **Granted by**: ${finding.grantedBy.map((item) => `\`${cell(item)}\``).join(", ")}`);
      }
      lines.push("");
      lines.push(finding.description);
      lines.push("");
      lines.push(`**Fix**: ${finding.remediation}`);
      lines.push("");
    }
  } else {
    lines.push("## Findings");
    lines.push("");
    lines.push("No findings. The known rule sets did not match this repository.");
    lines.push("");
  }

  if (report.warnings.length > 0) {
    lines.push("## Warnings");
    lines.push("");
    for (const warning of report.warnings) {
      lines.push(`- ${warning}`);
    }
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push(
    `Scanned ${report.stats.filesScanned} files (${report.stats.bytesScanned} bytes) in ${report.stats.durationMs}ms. Local-only scan: no network requests were made and no file was modified.`,
  );
  lines.push("");

  return lines.join("\n");
}
