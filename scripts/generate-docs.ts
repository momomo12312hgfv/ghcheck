import { mkdir, writeFile } from "node:fs/promises";
import { ANALYZER_LIST } from "../src/analyzers";
import { SEVERITIES, type Severity } from "../src/core/types";

const ORDER: Severity[] = [...SEVERITIES].reverse();

const lines: string[] = [];
lines.push("# Rule catalog");
lines.push("");
lines.push("Every rule ghcheck can report. Generated by `bun run docs`; do not edit by hand.");
lines.push("");

for (const analyzer of ANALYZER_LIST) {
  lines.push(`## ${analyzer.name} (\`${analyzer.id}\`)`);
  lines.push("");
  lines.push(analyzer.description);
  lines.push("");

  for (const severity of ORDER) {
    const rules = analyzer.rules.filter((rule) => rule.severity === severity);
    if (rules.length === 0) continue;

    lines.push(`### ${severity}`);
    lines.push("");
    for (const rule of rules) {
      lines.push(`#### \`${rule.id}\``);
      lines.push("");
      lines.push(`**${rule.title}**`);
      lines.push("");
      if (rule.confidence) {
        lines.push(`Confidence: ${rule.confidence}. The pattern is suspicious, the runtime behaviour is out of scope.`);
        lines.push("");
      }
      lines.push(rule.description);
      lines.push("");
      lines.push(`**Fix**: ${rule.remediation}`);
      lines.push("");
    }
  }
}

lines.push("---");
lines.push("");
lines.push("## Confidence");
lines.push("");
lines.push(
  "A rule that cannot be sure says so. `certain` means the pattern is unambiguous. `likely` means the pattern is suspicious but depends on runtime behaviour ghcheck does not observe, such as an agent instruction file that asks for a credential. Confidence never changes the score.",
);
lines.push("");
lines.push("## Suppression");
lines.push("");
lines.push("One syntax works for every rule, in every analyzer:");
lines.push("");
lines.push("```yaml");
lines.push("# ghcheck: ignore workflow.script-injection   # suppress that rule on this line");
lines.push("# ghcheck: ignore rule-a, rule-b              # several rules on this line");
lines.push("# ghcheck: ignore-all                          # every rule on this line");
lines.push("# ghcheck: ignore-file                         # every rule in this file");
lines.push("```");
lines.push("");

await mkdir("docs", { recursive: true });
await writeFile("docs/rules.md", `${lines.join("\n")}\n`, "utf8");

console.log(`Wrote docs/rules.md (${ANALYZER_LIST.reduce((sum, a) => sum + a.rules.length, 0)} rules)`);
